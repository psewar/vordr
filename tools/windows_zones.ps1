# Writes internal/agent/zone_table.go: Windows time zone IDs to IANA names (CLDR windowsZones, territory 001) as
# the ICU in .NET reports them. Run with PowerShell 7 on Windows from the repository root:
#   pwsh -NoProfile -File tools/windows_zones.ps1
# Zones ICU does not map stay out; the agent then reports no time zone for them.
$ErrorActionPreference = 'Stop'
$ziel = Join-Path $PSScriptRoot '..\internal\agent\zone_table.go'
if (-not $IsWindows) { Write-Output 'stopped: run this on Windows, it reads the system time zone list'; exit 2 }
$zeilen = foreach ($z in [System.TimeZoneInfo]::GetSystemTimeZones() | Sort-Object Id) {
    $iana = $null
    if ([System.TimeZoneInfo]::TryConvertWindowsIdToIanaId($z.Id, [ref] $iana)) { "`t""{0}"": ""{1}""," -f $z.Id, $iana }
}
$kopf = @(
    '// Code generated by tools/windows_zones.ps1; DO NOT EDIT.'
    ''
    'package agent'
    ''
    '// windowsZones maps a Windows time zone ID to its IANA name: CLDR windowsZones, territory 001, as reported by the'
    ('// ICU in .NET {0}. The IANA zone has the same rules as the Windows zone for the current era.' -f [System.Environment]::Version.Major)
    'var windowsZones = map[string]string{'
)
($kopf + $zeilen + '}') -join "`n" | Set-Content -Path $ziel -Encoding utf8NoBOM -NoNewline
Add-Content -Path $ziel -Value '' -Encoding utf8NoBOM
# gofmt aligns the values; the build checks it
$gofmt = (Get-Command gofmt -ErrorAction SilentlyContinue).Source
if (-not $gofmt -and (Test-Path "$env:ProgramFiles\Go\bin\gofmt.exe")) { $gofmt = "$env:ProgramFiles\Go\bin\gofmt.exe" }
if (-not $gofmt) { Write-Output "stopped: gofmt not found; install Go or run gofmt -w $ziel"; exit 3 }
& $gofmt -w $ziel
Write-Output ("{0} zones written to {1}" -f @($zeilen).Count, (Resolve-Path $ziel))
